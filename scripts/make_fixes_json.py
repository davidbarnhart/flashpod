#!/usr/bin/env python3
"""Generate flashpod/firmware/fixes.json from openpod's 1.6 and 1.7 fix folders.

    python3 scripts/make_fixes_json.py [--openpod ~/source/openpod-gen1] [--check]

`flashpod.card.inspect` reports WHICH openpod fixes a card's firmware carries:
a fix is present iff every one of its osos edits holds its patched bytes and
its appended code (if any) hashes to its sha256 (openpod firmware session,
bridge #1083). flashpod must not read openpod's repository at run time, so
this vendors what that test needs into fixes.json.

The fix files are read with OPENPOD'S OWN reader, tools/fw_fix.py
read_folder(): it refuses any block that isn't format 2 with exactly its six
keys, so a format change fails here instead of producing a silently wrong
table (bridge #1085).

The table is stamped with the folder it came from -- openpod commit (+ dirty
flag), the README's firmware-file sha256, and a hash over the fix files -- so
a stale copy is visible. --check regenerates in memory and exits 1 if the
committed fixes.json differs (ignoring nothing: regenerate and commit).
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "flashpod", "firmware", "fixes.json")
FOLDER = os.path.join("firmware", "1", "1.6")
#: 1.7 is 1.6 plus Refresh Library, with a different `version` fix. Its fixes
#: join the table: one that is byte for byte 1.6's is not added again, one
#: that differs is added as "<name>-1.7" (so a 1.6 card keeps reporting
#: exactly what it did), and a new one keeps its name.
FOLDER_17 = os.path.join("firmware", "1", "1.7")


def git(repo, *args):
    return subprocess.check_output(["git", "-C", repo] + list(args)).decode().strip()


def read_folder(openpod, rel):
    """(fixes, source stamp) for one fix folder, read with openpod's reader."""
    sys.path.insert(0, os.path.join(openpod, "tools"))
    import fw_fix                                   # openpod's reader
    folder = os.path.join(openpod, rel)
    parts = fw_fix.read_folder(folder)
    files = sorted(n for n in os.listdir(folder)
                   if n.endswith((".md", ".hex")) and n.lower() != "readme.md")
    h = hashlib.sha256()
    for n in files:
        h.update(n.encode() + b"\0")
        with open(os.path.join(folder, n), "rb") as f:
            h.update(f.read())
    readme = open(os.path.join(folder, "README.md")).read()
    m = re.search(r"firmware file inside the `\.ipsw` is [\d,]+ bytes, sha256\s+"
                  r"`([0-9a-f]{64})`", readme)
    fixes = []
    for p in parts:
        fixes.append({
            "name": p.stem,
            "title": p.title,
            "requires": list(p.requires),
            "made_for": p.made_for,
            "edits": [{"image": image, "at": "0x%08x" % at,
                       "patched": new.hex()}
                      for image, at, _stock, new, _why in p.edits],
            "append": ({"at": "0x%08x" % p.base, "bytes": len(p.blob),
                        "sha256": hashlib.sha256(p.blob).hexdigest()}
                       if p.blob else None),
        })
    dirty = bool(git(openpod, "status", "--porcelain", "--", rel, "tools"))
    return fixes, {
        "openpod_commit": git(openpod, "rev-parse", "HEAD"),
        "openpod_dirty": dirty,
        "folder": rel,
        "readme_firmware_sha256": m.group(1) if m else None,
        "fix_files_sha256": h.hexdigest(),
        "fix_files": len(files),
    }


def same_fix(a, b):
    return all(a[k] == b[k] for k in ("edits", "append"))


def build(openpod):
    fixes, src16 = read_folder(openpod, FOLDER)
    try:
        fixes17, src17 = read_folder(openpod, FOLDER_17)
    except OSError:
        fixes17, src17 = [], None
    have = {f["name"]: f for f in fixes}
    for f in fixes17:
        old = have.get(f["name"])
        if old is None:
            fixes.append(f)
        elif not same_fix(old, f):
            fixes.append(dict(f, name=f["name"] + "-1.7"))
    dirty = src16["openpod_dirty"] or bool(src17 and src17["openpod_dirty"])
    return {
        "_comment": "Generated by scripts/make_fixes_json.py from openpod's "
                    "firmware/1/1.6 and firmware/1/1.7 with openpod's "
                    "tools/fw_fix.py reader. Do not edit; regenerate. A fix "
                    "is present on a card iff all its osos edits hold "
                    "'patched' and its appended code hashes to 'sha256'. "
                    "1.7's fixes join 1.6's: one identical to 1.6's is not "
                    "repeated, one that differs is named '<name>-1.7'.",
        "source": src16,
        "source_1_7": src17,
        "fixes": fixes,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--openpod", default=os.path.expanduser("~/source/openpod-gen1"))
    ap.add_argument("--check", action="store_true")
    opts = ap.parse_args()
    table = build(os.path.abspath(opts.openpod))
    text = json.dumps(table, indent=1, sort_keys=True) + "\n"
    if opts.check:
        try:
            have = open(OUT).read()
        except OSError:
            have = ""
        if have != text:
            print("fixes.json is stale or missing: regenerate it")
            return 1
        print("fixes.json matches %s" % table["source"]["openpod_commit"][:12])
        return 0
    if table["source"]["openpod_dirty"]:
        print("warning: openpod's fix folder or tools have local changes; "
              "the stamp says so", file=sys.stderr)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote %s: %d fixes from openpod %s" % (
        OUT, len(table["fixes"]), table["source"]["openpod_commit"][:12]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
