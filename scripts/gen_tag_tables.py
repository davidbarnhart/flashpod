#!/usr/bin/env python3
"""Write rust/flashpod-core/src/tags/tables.rs: the tables the Rust tag
reader needs to behave exactly like mutagen under this Python.

    python3 scripts/gen_tag_tables.py

* GENRES: mutagen's ID3v1 genre names (TCON numbers, MP4 'gnre');
* ID3_FRAMES: the four-letter frame names mutagen knows (its `Frames`), which
  decide the ID3v2.4 frame-size guess and the bogus-extended-header check;
* DECIMAL_ZEROS: the code points of every Unicode decimal digit 0 (each run
  0..9 is contiguous), for str.isdecimal() and int();
* PY_SPACE: the characters str.isspace() / regex \\s / int() treat as space.

Regenerate after a Python or mutagen upgrade; the parity harness compares
the two readers file by file.
"""
import os
import sys
import unicodedata

import mutagen
from mutagen._constants import GENRES
from mutagen.id3 import Frames

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "rust", "flashpod-core", "src", "tags", "tables.rs")


def rust_str(s):
    return '"%s"' % "".join(
        c if 32 <= ord(c) < 127 and c not in '"\\' else "\\u{%x}" % ord(c)
        for c in s)


def main():
    zeros = []
    for cp in range(sys.maxunicode + 1):
        c = chr(cp)
        if c.isdecimal() and unicodedata.decimal(c) == 0:
            zeros.append(cp)
    # every decimal digit is zero + its value, within one run
    for cp in range(sys.maxunicode + 1):
        c = chr(cp)
        if c.isdecimal():
            v = unicodedata.decimal(c)
            assert cp - v in zeros and all(
                chr(cp - v + i).isdecimal() for i in range(10)), hex(cp)
    space = [cp for cp in range(sys.maxunicode + 1) if chr(cp).isspace()]
    frames = sorted(k for k in Frames if len(k) == 4)
    with open(OUT, "w") as f:
        f.write("// Generated by scripts/gen_tag_tables.py from Python %s, "
                "mutagen %s, Unicode %s. Do not edit.\n\n"
                % (sys.version.split()[0], mutagen.version_string,
                   unicodedata.unidata_version))
        f.write("pub const GENRES: [&str; %d] = [\n" % len(GENRES))
        for g in GENRES:
            f.write("    %s,\n" % rust_str(g))
        f.write("];\n\n")
        f.write("pub const ID3_FRAMES: [&str; %d] = [\n" % len(frames))
        for k in frames:
            f.write("    %s,\n" % rust_str(k))
        f.write("];\n\n")
        f.write("pub const DECIMAL_ZEROS: [u32; %d] = [\n" % len(zeros))
        for i in range(0, len(zeros), 8):
            f.write("    %s,\n" % ", ".join("0x%x" % z for z in zeros[i:i + 8]))
        f.write("];\n\n")
        f.write("pub const PY_SPACE: [u32; %d] = [\n" % len(space))
        for i in range(0, len(space), 8):
            f.write("    %s,\n" % ", ".join("0x%x" % z for z in space[i:i + 8]))
        f.write("];\n")
    print("wrote %s: %d genres, %d frames, %d digit runs, %d spaces"
          % (os.path.relpath(OUT, ROOT), len(GENRES), len(frames), len(zeros),
             len(space)))


if __name__ == "__main__":
    main()
